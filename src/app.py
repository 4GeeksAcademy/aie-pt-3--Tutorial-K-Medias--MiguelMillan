"""Cluster California census block groups and classify their cluster labels."""

from pathlib import Path
import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from joblib import dump
from sklearn.cluster import KMeans
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler


ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "data" / "raw" / "housing.csv"
PROCESSED_DIR = ROOT / "data" / "processed"
MODEL_DIR = ROOT / "models"
FEATURES = ["Latitude", "Longitude", "MedInc"]
RANDOM_STATE = 42


def main() -> None:
	"""Fit both models, save their artifacts, and report test-set results."""
	if not DATA_PATH.exists():
		raise FileNotFoundError(
			f"Dataset not found at {DATA_PATH}. Download housing.csv into data/raw/."
		)

	data = pd.read_csv(DATA_PATH)
	missing_columns = set(FEATURES).difference(data.columns)
	if missing_columns:
		raise ValueError(f"Dataset is missing required columns: {sorted(missing_columns)}")

	# Use only the requested variables and discard incomplete observations.
	data = data[FEATURES].dropna().reset_index(drop=True)
	train_data, test_data = train_test_split(
		data, test_size=0.2, random_state=RANDOM_STATE
	)
	X_train = train_data[FEATURES]
	X_test = test_data[FEATURES]

	# Scale features so latitude/longitude and median income contribute on
	# comparable scales to the Euclidean distances used by K-Means.
	kmeans = make_pipeline(
		StandardScaler(),
		KMeans(n_clusters=6, random_state=RANDOM_STATE, n_init=10),
	)
	y_train = kmeans.fit_predict(X_train)
	y_test_kmeans = kmeans.predict(X_test)

	# Train a supervised model to reproduce the cluster assignments on unseen
	# rows. These are pseudo-labels generated by K-Means, not ground truth.
	classifier = RandomForestClassifier(
		n_estimators=300,
		class_weight="balanced",
		random_state=RANDOM_STATE,
		n_jobs=-1,
	)
	classifier.fit(X_train, y_train)
	y_test_classifier = classifier.predict(X_test)
	agreement = accuracy_score(y_test_kmeans, y_test_classifier)

	# Save cluster labels for the full dataset, assigning held-out points with
	# the already-fitted K-Means model (no refitting on the test set).
	clustered_data = data.copy()
	clustered_data["cluster"] = kmeans.predict(data[FEATURES])
	PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
	MODEL_DIR.mkdir(parents=True, exist_ok=True)
	clustered_data.to_csv(PROCESSED_DIR / "housing_clusters.csv", index=False)

	dump(kmeans, MODEL_DIR / "kmeans_housing.joblib")
	dump(classifier, MODEL_DIR / "housing_cluster_classifier.joblib")

	# Plot the training assignments and held-out K-Means predictions together.
	train_labels = pd.Series(y_train, index=X_train.index)
	test_labels = pd.Series(y_test_kmeans, index=X_test.index)
	fig, ax = plt.subplots(figsize=(12, 8))
	scatter = ax.scatter(
		X_train["Longitude"],
		X_train["Latitude"],
		c=train_labels,
		cmap="tab10",
		s=9,
		alpha=0.55,
		label="Train",
	)
	ax.scatter(
		X_test["Longitude"],
		X_test["Latitude"],
		c=test_labels,
		cmap="tab10",
		marker="x",
		s=18,
		alpha=0.75,
		label="Test (K-Means predict)",
	)
	ax.set(title="California Housing: K-Means (6 clusters)", xlabel="Longitude", ylabel="Latitude")
	ax.legend(loc="best")
	fig.colorbar(scatter, ax=ax, label="Cluster")
	fig.tight_layout()
	fig.savefig(PROCESSED_DIR / "housing_clusters.png", dpi=160)
	plt.close(fig)

	report = classification_report(
		y_test_kmeans, y_test_classifier, output_dict=True, zero_division=0
	)
	metrics = {
		"rows": len(data),
		"train_rows": len(X_train),
		"test_rows": len(X_test),
		"clusters": 6,
		"classifier_agreement_with_kmeans": agreement,
		"confusion_matrix": confusion_matrix(y_test_kmeans, y_test_classifier).tolist(),
		"classification_report": report,
		"interpretation": (
			"Scores measure how closely the supervised classifier reproduces "
			"K-Means pseudo-labels; they are not accuracy against independently "
			"verified geographic regions."
		),
	}
	with (PROCESSED_DIR / "metrics.json").open("w", encoding="utf-8") as metrics_file:
		json.dump(metrics, metrics_file, indent=2)

	print(f"Rows: {len(data)} (train={len(X_train)}, test={len(X_test)})")
	print("Cluster counts in training set:")
	print(pd.Series(y_train).value_counts().sort_index().to_string())
	print(f"Classifier agreement with K-Means on test: {agreement:.4f}")
	print("Test-set classification report (K-Means labels as reference):")
	print(classification_report(y_test_kmeans, y_test_classifier, zero_division=0))
	print(f"Saved models in {MODEL_DIR}")
	print(f"Saved plot, assigned data, and metrics in {PROCESSED_DIR}")


if __name__ == "__main__":
	main()
